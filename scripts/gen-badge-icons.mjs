// Generates lib/badge/icons.ts from the installed lucide-react package.
//
// The badge SVG is rendered on the server as a raw string, so it needs each
// icon's node data ([tag, attributes] on a 24x24 viewBox) inlined rather than a
// React component. This script extracts that node data straight from lucide-react
// so we reuse the icon library instead of hand-copying path data.
//
// Usage:  node scripts/gen-badge-icons.mjs
// To add/remove icons: edit the `names` list below and re-run.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const ICON_DIR = path.join(
  ROOT,
  "node_modules/lucide-react/dist/esm/icons"
);
const OUT = path.join(ROOT, "lib/badge/icons.ts");

// Curated set shown in the badge icon picker. Keys are lucide icon file names
// (kebab-case) and double as the `icon` query-param values.
const names = [
  "heart", "heart-handshake", "hand-heart", "star", "sparkles", "smile", "laugh", "party-popper", "flame", "zap",
  "thumbs-up", "thumbs-down", "award", "trophy", "medal", "crown", "gem", "gift", "handshake", "quote",
  "badge-check", "circle-check", "message-circle", "message-square", "bell", "megaphone", "mail", "send", "share-2", "link",
  "users", "user-plus", "mic", "bookmark", "tag", "bug", "rocket", "git-fork", "code", "terminal",
  "lightbulb", "wrench", "book-open", "feather", "pen-line", "coffee", "eye", "target",
];

// Extracts the icon node array (the 2nd argument to createLucideIcon) from an
// icon module and drops lucide's internal `key` attribute.
function nodesFor(name) {
  const file = path.join(ICON_DIR, `${name}.js`);
  if (!fs.existsSync(file)) return null;
  const src = fs.readFileSync(file, "utf8");
  const start = src.indexOf("createLucideIcon(");
  const open = src.indexOf("[", start);
  let depth = 0;
  let end = -1;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === "[") depth++;
    else if (c === "]" && --depth === 0) {
      end = i;
      break;
    }
  }
  // The extracted slice is a plain array/object literal of geometry data.
  const nodes = eval(src.slice(open, end + 1));
  return nodes.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}

const entries = [];
const missing = [];
for (const name of names) {
  const nd = nodesFor(name);
  if (!nd) missing.push(name);
  else entries.push([name, nd]);
}
if (missing.length) {
  console.warn("Skipped (not found in lucide-react):", missing.join(", "));
}

const body = entries
  .map(([name, nd]) => {
    const nodeStr = nd
      .map(([tag, attrs]) => `    [${JSON.stringify(tag)}, ${JSON.stringify(attrs)}],`)
      .join("\n");
    return `  ${JSON.stringify(name)}: [\n${nodeStr}\n  ],`;
  })
  .join("\n");

const file = `// GENERATED by scripts/gen-badge-icons.mjs from lucide-react (ISC). Do not edit
// the registry by hand; edit the \`names\` list in that script and re-run.
//
// Each entry is a lucide icon node list ([tag, attributes]) on a 24x24 viewBox,
// rendered as an outline (stroke) mark inside the badge SVG. Keys double as the
// \`icon\` query-param values and are the single source of truth shared by the
// server SVG renderer and the client icon picker.

export type IconNode = [string, Record<string, string | number>];

export const BADGE_ICONS: Record<string, IconNode[]> = {
${body}
};

export type BadgeIconKey = keyof typeof BADGE_ICONS;

export const BADGE_ICON_KEYS = Object.keys(BADGE_ICONS) as BadgeIconKey[];

export const DEFAULT_ICON: BadgeIconKey = "heart";

export function isValidIcon(key: string | null | undefined): key is BadgeIconKey {
  return !!key && Object.prototype.hasOwnProperty.call(BADGE_ICONS, key);
}

// Renders the icon as an outline mark (matches lucide's stroke style) using the
// given color. Returned string is the inner SVG (no wrapping <svg>).
export function renderIcon(key: BadgeIconKey, color: string): string {
  const nodes = BADGE_ICONS[key];
  const inner = nodes
    .map(([tag, attrs]) => {
      const attrStr = Object.entries(attrs)
        .map(([k, v]) => \`\${k}="\${v}"\`)
        .join(" ");
      return \`<\${tag} \${attrStr} />\`;
    })
    .join("");
  return \`<g fill="none" stroke="\${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${inner}</g>\`;
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, file);
console.log(`Wrote ${path.relative(ROOT, OUT)} with ${entries.length} icons.`);
